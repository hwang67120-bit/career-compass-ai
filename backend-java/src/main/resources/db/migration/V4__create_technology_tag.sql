CREATE TABLE technology_tag (
    id UUID PRIMARY KEY,
    tag_key VARCHAR(100) NOT NULL,
    normalized_key VARCHAR(100) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    category VARCHAR(30) NOT NULL,
    default_display_order INTEGER NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_technology_tag_key UNIQUE (tag_key),
    CONSTRAINT uk_technology_tag_normalized_key UNIQUE (normalized_key),
    CONSTRAINT ck_technology_tag_category CHECK (
        category IN (
            'LANGUAGE',
            'FRAMEWORK_LIBRARY',
            'DATABASE',
            'INFRASTRUCTURE_CLOUD',
            'TOOL_PLATFORM',
            'OTHER'
        )
    ),
    CONSTRAINT ck_technology_tag_display_order CHECK (default_display_order > 0)
);

CREATE TABLE technology_tag_alias (
    id UUID PRIMARY KEY,
    technology_tag_id UUID NOT NULL,
    alias VARCHAR(100) NOT NULL,
    normalized_alias VARCHAR(100) NOT NULL,
    CONSTRAINT fk_technology_tag_alias_tag
        FOREIGN KEY (technology_tag_id) REFERENCES technology_tag (id) ON DELETE CASCADE,
    CONSTRAINT uk_technology_tag_alias_normalized UNIQUE (normalized_alias)
);

CREATE INDEX idx_technology_tag_default_display
    ON technology_tag (active, default_display_order, display_name);

CREATE INDEX idx_technology_tag_alias_tag
    ON technology_tag_alias (technology_tag_id);

